import { getCollection, type CollectionEntry } from 'astro:content';
import { buildMeta, type PageMeta } from '../meta';
import { site } from '../site.config';
import { DEFAULT_LOCALE, LOCALES, hrefOfKey, hrefOfPath, isLocale, keyOf, localeOfPath, prefixOf, routeParams, type Locale } from '../urls';

/**
 * Migrated pages in Starlight's `docs` collection, by the kit's URL rules (urls.ts) and head data
 * (meta.ts). Starlight routes the pages (id = old path, ids.ts); this module answers what Starlight
 * can't: old href forms, translations by `translationKey`, aliases, and which pages are Starlight's
 * fallback copies. Used by route-data.ts, the overrides next to it and the alias routes.
 */

export type DocsEntry = CollectionEntry<'docs'>;

/** Route key of a Starlight id: 'index' or '' → '/', 'en/kontakt' → '/en/kontakt'. */
export const keyOfId = (id: string): string => keyOf(`/${id === 'index' ? '' : id}`);

/** The href of an entry: its old path as the old site linked it (/kontakt, /en/, /about/, /about.html). */
export function hrefOf(entry: DocsEntry): string {
  if (entry.data.oldUrl) {
    try {
      return hrefOfPath(new URL(entry.data.oldUrl).pathname);
    } catch {
      // fall through
    }
  }
  const key = keyOfId(entry.id);
  const first = key.split('/')[1] ?? '';
  return hrefOfKey(key, key === '/' || (isLocale(first) && key === `/${first}`));
}

/** Language of an entry: its `lang` if that is a site locale, else its URL prefix. */
export function localeOf(entry: DocsEntry): Locale {
  const lang = entry.data.lang?.toLowerCase().replace('_', '-') ?? '';
  for (const candidate of [lang, lang.split('-')[0]]) if (isLocale(candidate)) return candidate;
  return localeOfPath(hrefOf(entry));
}

/** A readable label for a path segment (folder names of autogenerated sidebar groups, empty titles). */
export function labelOfKey(key: string): string {
  const last = key.split('/').filter(Boolean).at(-1);
  if (!last) return site.name;
  const words = last.replace(/[-_]+/g, ' ');
  return words.charAt(0).toLocaleUpperCase() + words.slice(1);
}

export const titleOf = (entry: DocsEntry): string => entry.data.title.trim() || labelOfKey(keyOfId(entry.id));

let cached: Promise<Map<string, DocsEntry>> | undefined;

/** Routable entries by route key: drafts only outside production builds, as Starlight does. */
export function entriesByKey(): Promise<Map<string, DocsEntry>> {
  if (import.meta.env.DEV) return loadEntries();
  return (cached ??= loadEntries());
}

async function loadEntries(): Promise<Map<string, DocsEntry>> {
  const entries = await getCollection('docs', ({ data }) => import.meta.env.MODE !== 'production' || !data.draft);
  return new Map(entries.map((entry) => [keyOfId(entry.id), entry]));
}

/** The page in every language that has it: itself plus the entries with the same translationKey (not noindex). */
export function translationsOf(entry: DocsEntry, all: Iterable<DocsEntry>): Record<Locale, string> {
  const result: Record<Locale, string> = { [localeOf(entry)]: hrefOf(entry) };
  const key = entry.data.translationKey;
  if (!key || entry.data.noindex) return result;
  for (const other of all) {
    if (other === entry || other.data.translationKey !== key || other.data.noindex) continue;
    result[localeOf(other)] ??= hrefOf(other);
  }
  return result;
}

/** Head data of an entry at its main URL, or at an alias `path` (canonical = main URL, no hreflang). */
export async function metaOf(entry: DocsEntry, path?: string): Promise<PageMeta> {
  const main = hrefOf(entry);
  const isAlias = !!path && path !== main;
  return buildMeta({
    title: titleOf(entry),
    description: entry.data.description,
    locale: localeOf(entry),
    path: path ?? main,
    canonical: main,
    translations: isAlias ? undefined : translationsOf(entry, (await entriesByKey()).values()),
    noindex: entry.data.noindex,
    image: entry.data.featuredImage,
  });
}

/**
 * Keys of the pages Starlight builds as fallbacks: every default-language page again under each
 * other language prefix (/kontakt → /en/kontakt) where that language has no page with the same
 * path. With translated slugs those are duplicates the old site never had; the route middleware
 * marks them and integrations/starlight-migration.mjs deletes them after the build.
 */
export async function fallbackKeys(): Promise<Set<string>> {
  const byKey = await entriesByKey();
  const defaultPrefix = prefixOf(DEFAULT_LOCALE);
  const others = LOCALES.filter((l) => l !== DEFAULT_LOCALE).map(prefixOf);
  const keys = new Set<string>();
  for (const key of byKey.keys()) {
    const segs = key.split('/').filter(Boolean);
    const isDefault = defaultPrefix ? segs[0] === defaultPrefix : !others.includes(segs[0] ?? '');
    if (!isDefault) continue;
    const rest = defaultPrefix ? segs.slice(1) : segs;
    for (const prefix of others) {
      const candidate = `/${[prefix, ...rest].join('/')}`;
      if (!byKey.has(candidate)) keys.add(candidate);
    }
  }
  return keys;
}

/** getStaticPaths of the alias routes (src/pages/[...alias].astro and [...alias]/index.astro). */
export async function aliasPaths(index: boolean) {
  const byKey = await entriesByKey();
  const seen = new Set<string>();
  const out: { params: { alias: string | undefined }; props: { entry: DocsEntry; path: string } }[] = [];
  for (const entry of byKey.values()) {
    const main = keyOfId(entry.id);
    for (const alias of entry.data.aliases ?? []) {
      const path = alias.replace(/^[a-z]+:\/\/[^/]+/i, '') || '/';
      const key = keyOf(path);
      // A real page lives there, or it is the entry's own URL.
      if (key === '/' || key === main || byKey.has(key) || seen.has(key)) continue;
      const params = routeParams(path);
      if (params.index !== index) continue;
      seen.add(key);
      out.push({ params: { alias: params.path }, props: { entry, path: hrefOfPath(path) } });
    }
  }
  return out;
}

/** Name of a language in that language (Deutsch, English), as Starlight labels its locales by default. */
export function languageLabel(lang: string): string {
  try {
    const name = new Intl.DisplayNames([lang], { type: 'language' }).of(lang) ?? lang;
    return name.charAt(0).toLocaleUpperCase(lang) + name.slice(1);
  } catch {
    return lang;
  }
}
