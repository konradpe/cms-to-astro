import { defineRouteMiddleware, type StarlightRouteData } from '@astrojs/starlight/route-data';
import type { PageMeta } from '../meta';
import { LOCALES, homeOf, keyOf } from '../urls';
import { entriesByKey, fallbackKeys, hrefOf, keyOfId, labelOfKey, metaOf, titleOf } from './docs';

/**
 * Starlight route middleware (astro.config.mjs `routeMiddleware`). Runs before every Starlight page
 * renders: docs pages, the kit's pages (StarlightShell) and alias pages (AliasPage).
 *   - head: canonical = the old URL; hreflang from `translationKey` instead of Starlight's
 *     same-path pairing; robots noindex; og:image from `featuredImage`;
 *   - language: <html lang> from the page (`lang`, else URL prefix); locals.migration.meta feeds
 *     the language switcher (LanguageSelect.astro);
 *   - navigation: sidebar, prev/next and site-title links in the old URL form (/kontakt, /en/);
 *     Starlight's fallback copies left out of the sidebar; autogenerated folder groups named after
 *     their section page (/leistungen groups /leistungen/*), else after the folder;
 *   - Starlight's fallback copies themselves (/en/kontakt showing /kontakt): noindex, not searchable,
 *     marked for integrations/starlight-migration.mjs, which deletes them after the build.
 */

type Head = StarlightRouteData['head'];
type SidebarEntry = StarlightRouteData['sidebar'][number];
type SidebarLink = Extract<SidebarEntry, { type: 'link' }>;
type SidebarGroup = Extract<SidebarEntry, { type: 'group' }>;

const metaTag = (attrs: Record<string, string>): Head[number] => ({ tag: 'meta', attrs });
const isInternal = (href: string) => href.startsWith('/') && !href.startsWith('//');
const flatten = (entries: SidebarEntry[]): SidebarLink[] => entries.flatMap((e) => (e.type === 'link' ? [e] : flatten(e.entries)));

export const onRequest = defineRouteMiddleware(async (context) => {
  const route = context.locals.starlightRoute;
  if (route.isFallback) {
    route.entry.data.pagefind = false;
    route.head.push(metaTag({ name: 'robots', content: 'noindex' }), metaTag({ name: 'migration', content: 'fallback' }));
    return;
  }

  let page = context.locals.migration; // set by StarlightShell (kit pages) and AliasPage
  if (!page) {
    const entry = (await entriesByKey()).get(keyOfId(route.id));
    if (!entry) return; // a StarlightPage of the project itself: Starlight's defaults
    page = { meta: await metaOf(entry) };
    context.locals.migration = page;
    if (!entry.data.title.trim()) {
      route.entry.data.title = page.meta.heading;
      for (const tag of route.head) if (tag.tag === 'title') tag.content = page.meta.title;
    }
    // Search results link to the old URL (Pagefind would use the file path, /kontakt.html in preserve style).
    route.head.push(metaTag({ 'data-pagefind-meta': 'url[content]', content: page.meta.path ?? hrefOf(entry) }));
    if (entry.data.blocks?.length) {
      console.warn(`[migration] ${entry.filePath}: \`blocks\` are not rendered in the Starlight recipe; use Starlight's MDX components (references/themes/starlight.md).`);
    }
  }

  const { meta } = page;
  route.lang = route.entryMeta.lang = meta.lang;
  route.head = headFor(route.head, meta);
  route.siteTitleHref = homeOf(meta.locale);
  await fixNavigation(route);
});

/** Starlight's head with canonical, og:url, hreflang, robots and og:image from the kit's PageMeta. */
function headFor(head: Head, meta: PageMeta): Head {
  const kept = head.filter(({ tag, attrs = {} }) => {
    if (tag === 'link') return attrs.rel !== 'canonical' && !(attrs.rel === 'alternate' && attrs.hreflang);
    if (tag === 'meta') return attrs.property !== 'og:url' && !(meta.noindex && attrs.name === 'robots') && !(meta.image && attrs.property === 'og:image');
    return true;
  });
  const added: Head = [];
  if (meta.canonical) added.push({ tag: 'link', attrs: { rel: 'canonical', href: meta.canonical } }, metaTag({ property: 'og:url', content: meta.canonical }));
  for (const alt of meta.alternates) added.push({ tag: 'link', attrs: { rel: 'alternate', hreflang: alt.hreflang, href: alt.href } });
  if (meta.noindex) added.push(metaTag({ name: 'robots', content: 'noindex' }));
  if (meta.image) added.push(metaTag({ property: 'og:image', content: meta.image }));
  return [...kept, ...added];
}

async function fixNavigation(route: StarlightRouteData) {
  const byKey = await entriesByKey();
  const fallbacks = await fallbackKeys();
  // Language home pages are left out of the generated sidebar: the site title links there.
  const homes = new Set(LOCALES.map((l) => keyOf(homeOf(l))));
  const dropped = new Set<string>();

  /** Old href form and a label for empty titles; undefined for a fallback copy or a home page. */
  const fixLink = (link: SidebarLink): SidebarLink | undefined => {
    if (!isInternal(link.href)) return link;
    const key = keyOf(link.href);
    if (fallbacks.has(key) || ('autogenerate' in link && homes.has(key))) {
      dropped.add(key);
      return undefined;
    }
    const entry = byKey.get(key);
    if (entry) {
      link.href = hrefOf(entry);
      if (!link.label.trim()) link.label = titleOf(entry);
    }
    return link;
  };

  const fixEntries = (entries: SidebarEntry[]): SidebarEntry[] =>
    entries.flatMap((item): SidebarEntry[] => {
      if (item.type === 'link') {
        const link = fixLink(item);
        return link ? [link] : [];
      }
      item.entries = fixEntries(item.entries);
      if (!item.entries.length) return [];
      if ('autogenerate' in item) nameGroup(item);
      return [item];
    });

  route.sidebar = fixEntries(route.sidebar);

  // prev/next were computed from the unfiltered sidebar: replace dropped links by the real neighbours.
  const flat = flatten(route.sidebar);
  const current = flat.findIndex((link) => link.isCurrent);
  for (const [dir, step] of [['prev', -1], ['next', 1]] as const) {
    const link = route.pagination[dir];
    if (!link || !isInternal(link.href)) continue;
    route.pagination[dir] = dropped.has(keyOf(link.href)) || fallbacks.has(keyOf(link.href)) ? (current >= 0 ? flat[current + step] : undefined) : fixLink(link);
  }
}

/**
 * Starlight labels an autogenerated group with its folder name (leistungen). Use the title of the
 * folder's own page (/leistungen next to /leistungen/*) instead, else the folder name made readable.
 */
function nameGroup(group: SidebarGroup) {
  const folder = group.label;
  const keys = flatten(group.entries).filter((l) => isInternal(l.href)).map((l) => keyOf(l.href));
  const section = group.entries.find((e): e is SidebarLink => {
    if (e.type !== 'link' || !isInternal(e.href)) return false;
    const key = keyOf(e.href);
    return keys.every((k) => k === key || k.startsWith(`${key}/`)) && (keys.length > 1 || key.split('/').at(-1) === folder);
  });
  group.label = section ? section.label : labelOfKey(folder);
}
